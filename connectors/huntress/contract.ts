import type { Scope, Severity, SnapshotItem, NormalizedEvent } from '../../packages/core/contracts.ts';
import type { IdentityRead } from '../contracts.ts';
import { record, list, id, optionalId, optionalText, oneOf, optionalTime, requiredTime, contractMismatch } from '../dto.ts';

/**
 * Huntress API v1 contract as Atlas reads it. Verified on 2026-10-07 against the official API reference
 * (https://api.huntress.io/docs, Swagger 2.0, info.version 1.0.0) — see connectors/CONTRACTS.md. Every property is
 * optional in that spec, so each field Atlas reads is checked explicitly; unknown fields are ignored.
 */
export const HUNTRESS_CONTRACT_VERSION = 'huntress-api-v1/2026-10-07';
export const HUNTRESS_BASE_URL = 'https://api.huntress.io';
/** Documented severities map one to one onto Atlas severities (the source's own scale, no Atlas threshold involved). */
export const HUNTRESS_SEVERITIES = ['low', 'high', 'critical'] as const;
export const huntressSeverity: Readonly<Record<(typeof HUNTRESS_SEVERITIES)[number], Severity>> = Object.freeze({ low: 'LOW', high: 'HIGH', critical: 'CRITICAL' });
/** Statuses documented on the incident report object; `draft` only appears when fetched by ID. Open in Atlas terms: `sent`. */
export const HUNTRESS_INCIDENT_STATUSES = ['sent', 'closed', 'dismissed', 'draft'] as const;

export interface HuntressPage<T> { items: T[]; nextPageToken: string | null }
/** List responses: the plural resource key and a pagination object whose next_page_token is present only if there is more. */
export function parsePage<T>(body: unknown, key: string, item: (value: unknown) => T): HuntressPage<T> {
  const root = record(body, 'root');
  const items = list(root[key], key).map(item);
  const pagination = record(root.pagination, 'pagination');
  const token = pagination.next_page_token;
  if (token === null || token === undefined) return { items, nextPageToken: null };
  if (typeof token !== 'string' || !/^[A-Za-z0-9_=+/.-]{1,512}$/.test(token)) throw contractMismatch('pagination.next_page_token');
  return { items, nextPageToken: token };
}

export interface HuntressAgent { id: string; organizationId: string; hostname: string | null; platform: string | null; updatedAt: string | null }
export function parseAgent(value: unknown): HuntressAgent {
  const a = record(value, 'agents[]');
  return { id: id(a.id, 'agent.id'), organizationId: id(a.organization_id, 'agent.organization_id'),
    hostname: optionalText(a.hostname, 'agent.hostname', 255), platform: optionalText(a.platform, 'agent.platform', 32),
    updatedAt: optionalTime(a.updated_at, 'agent.updated_at') };
}

export interface HuntressIncident {
  id: string; organizationId: string; agentId: string | null; severity: (typeof HUNTRESS_SEVERITIES)[number];
  status: (typeof HUNTRESS_INCIDENT_STATUSES)[number]; subject: string | null; sentAt: string | null; updatedAt: string;
}
export function parseIncident(value: unknown): HuntressIncident {
  const r = record(value, 'incident_reports[]');
  return { id: id(r.id, 'incident.id'), organizationId: id(r.organization_id, 'incident.organization_id'),
    agentId: optionalId(r.agent_id, 'incident.agent_id'), severity: oneOf(r.severity, 'incident.severity', HUNTRESS_SEVERITIES),
    status: oneOf(r.status, 'incident.status', HUNTRESS_INCIDENT_STATUSES), subject: optionalText(r.subject, 'incident.subject', 200),
    sentAt: optionalTime(r.sent_at, 'incident.sent_at'), updatedAt: requiredTime(r.updated_at, 'incident.updated_at') };
}

/** GET /v1/organizations/{id} → { organization: { id, ... } }. */
export function parseOrganizationId(body: unknown): string {
  return id(record(record(body, 'root').organization, 'organization').id, 'organization.id');
}

export function incidentItem(r: HuntressIncident): SnapshotItem {
  return { source: 'huntress', resourceType: 'incident', externalId: r.id, title: r.subject ?? 'Huntress incident report', status: r.status,
    severity: huntressSeverity[r.severity], priority: null, device: r.agentId ? { resourceType: 'agent', externalId: r.agentId } : null,
    occurredAt: r.sentAt, updatedAt: r.updatedAt };
}
export function agentIdentity(a: HuntressAgent, fetchedAt: string): IdentityRead {
  const attributes: Record<string, string> = {};
  if (a.hostname) attributes.hostname = a.hostname;
  if (a.platform) attributes.platform = a.platform;
  return { resourceType: 'agent', externalId: a.id, attributes, observedAt: a.updatedAt ?? fetchedAt };
}
/**
 * Event for the durable pipeline (task 1.6). The revision is updated_at — the source's documented update timestamp
 * (docs/03: a stable source update timestamp where the vendor has no revision). The summary is the autogenerated
 * one-line subject; the analyst summary and body are not copied.
 */
export function incidentEvent(scope: Scope, connectionId: string, r: HuntressIncident, receivedAt: string): NormalizedEvent {
  const subject = r.subject ?? 'Huntress incident report';
  return { workspaceId: scope.workspaceId, clientId: scope.clientId, source: 'huntress', connectionId, resourceType: 'incident',
    externalEventId: r.id, revision: r.updatedAt, externalDevice: r.agentId ? { resourceType: 'agent', externalId: r.agentId } : null,
    occurredAt: r.sentAt ?? r.updatedAt, receivedAt, kind: 'SECURITY_INCIDENT', sourceSeverity: huntressSeverity[r.severity],
    summary: subject, facts: { signal: subject } };
}
