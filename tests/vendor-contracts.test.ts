test('Huntress: fixtures parse into the Atlas contract; severity maps one to one; analyst summary and body are not copied', () => {
  const page = huntress.parsePage(vendorFixture('huntress/incident-reports-sent.json'), 'incident_reports', huntress.parseIncident);
  assert.equal(page.nextPageToken, null);
  const items = page.items.map(huntress.incidentItem);
  assert.deepEqual(items.map(i => [i.externalId, i.severity, i.status, i.device?.externalId ?? null]), [['9001', 'CRITICAL', 'sent', '207001'], ['9002', 'LOW', 'sent', null]]);
  assert.ok(!JSON.stringify(items).includes('Analyst narrative') && !JSON.stringify(items).includes('Autogenerated details'));
  assert.deepEqual(huntress.huntressSeverity, { low: 'LOW', high: 'HIGH', critical: 'CRITICAL' });
  const event = huntress.incidentEvent({ workspaceId: 'w', clientId: 'c' }, 'conn', page.items[0]!, '2026-10-07T07:00:00.000Z');
  assert.deepEqual([event.kind, event.resourceType, event.externalEventId, event.revision, event.sourceSeverity, event.externalDevice],
    ['SECURITY_INCIDENT', 'incident', '9001', '2026-10-07T06:45:00.000Z', 'CRITICAL', { resourceType: 'agent', externalId: '207001' }]);
  const agents = huntress.parsePage(vendorFixture('huntress/agents-page-1.json'), 'agents', huntress.parseAgent);
  assert.equal(agents.nextPageToken, 'MjAyNi0xMC0wN1QwNzo1NTowMFo');
  const identity = huntress.agentIdentity(agents.items[0]!, 'unused');
  assert.deepEqual(identity, { resourceType: 'agent', externalId: '207001', attributes: { hostname: 'GASTA-LT-07', platform: 'windows' }, observedAt: '2026-10-07T07:55:00.000Z' });
  assert.ok(!JSON.stringify(identity).includes('203.0.113.7') && !JSON.stringify(identity).includes('SYNTH-07'), 'addresses and serials are not copied');
});

test('Atera: fixtures parse into the Atlas contract; requester contact data and comments are not copied; zone-less times read as UTC', () => {
  const first = atera.parsePage(vendorFixture('atera/tickets-open-page-1.json'), atera.parseTicket);
  assert.deepEqual([first.page, first.totalPages, first.totalItemCount], [1, 2, 2]);
  const item = atera.ticketItem(first.items[0]!);
  assert.deepEqual(item, { source: 'atera', resourceType: 'ticket', externalId: '30001', title: 'Disk capacity follow-up on GASTA-LT-07 (synthetic)',
    status: 'Open', severity: null, priority: 'High', device: null, occurredAt: '2026-10-07T06:50:00.000Z', updatedAt: null });
  for (const pii of ['kari@example.invalid', 'Kari', '+47', 'Free-text comment', 'tech@example.invalid']) assert.ok(!JSON.stringify(item).includes(pii), pii);
  const agents = atera.parsePage(vendorFixture('atera/agents-customer.json'), atera.parseAgent);
  assert.deepEqual(atera.agentIdentity(agents.items[0]!, 'unused'),
    { resourceType: 'agent', externalId: '107001', attributes: { hostname: 'GASTA-LT-07', osType: 'Windows 11' }, observedAt: '2026-10-07T07:58:00.000Z' });
  assert.equal(atera.parseCustomerId(vendorFixture('atera/customer.json')), '5001');
  assert.deepEqual(atera.ateraAlertSeverity, { Information: 'INFO', Warning: 'MEDIUM', Critical: 'CRITICAL' });
});

test('contract drift fails closed as PERMANENT and names the field, never the value', () => {
  const base = { id: 1, organization_id: 7001, severity: 'high', status: 'sent', updated_at: '2026-10-07T00:00:00Z' };
  const cases: [Record<string, unknown>, string][] = [[{ severity: 'urgent' }, 'incident.severity'], [{ status: 'auto_remediating' }, 'incident.status'],
    [{ updated_at: undefined }, 'incident.updated_at'], [{ id: '1' }, 'incident.id'], [{ id: 2 ** 53 + 2 }, 'incident.id'],
    [{ updated_at: '2026-10-07T00:00:00' }, 'incident.updated_at'], [{ subject: 42 }, 'incident.subject'], [{ organization_id: null }, 'incident.organization_id']];
  for (const [change, field] of cases) {
    assert.throws(() => huntress.parseIncident({ ...base, ...change }),
      (e: AtlasError) => e.code === 'UPSTREAM_CONTRACT_MISMATCH' && e.kind === 'PERMANENT' && e.details.field === field && !JSON.stringify(e).includes('urgent'), field);
  }
  assert.throws(() => huntress.parsePage({ incident_reports: [] }, 'incident_reports', huntress.parseIncident), /UPSTREAM_CONTRACT_MISMATCH/, 'pagination object missing');
  assert.throws(() => huntress.parsePage({ agents: [], pagination: { next_page_token: 'a b' } }, 'agents', huntress.parseAgent), /UPSTREAM_CONTRACT_MISMATCH/);
  assert.throws(() => atera.parsePage({ items: [], page: '1', totalPages: 1, totalItemCount: 0 }, atera.parseTicket), /UPSTREAM_CONTRACT_MISMATCH/);
  assert.throws(() => atera.parseTicket({ TicketID: 1, CustomerID: 5001, TicketStatus: 'Open', TicketPriority: 'Urgent' }), /UPSTREAM_CONTRACT_MISMATCH/);
  assert.deepEqual(atera.parsePage({ items: null, page: 1, totalPages: 0, totalItemCount: 0 }, atera.parseTicket).items, [], 'items is nullable in the export');
});

test('vendor HTTP failures are classified without the URL, headers, credential or body', async () => {
  const url = new URL('https://api.huntress.io/v1/agents?organization_id=7001');
  const call = (reply: Reply, limits = { timeoutMs: 1000, maxBodyBytes: 1000 }) =>
    getJson(mockVendor(() => reply).transport, url, { Authorization: 'Basic c2VjcmV0LXZhbHVl' }, limits);
  const expectations: [Reply, string, string][] = [[{ status: 429, headers: { 'retry-after': '30' } }, 'UPSTREAM_RATE_LIMITED', 'TRANSIENT'],
    [{ status: 401 }, 'UPSTREAM_AUTH_FAILED', 'PERMANENT'], [{ status: 403 }, 'UPSTREAM_AUTH_FAILED', 'PERMANENT'], [{ status: 404 }, 'UPSTREAM_NOT_FOUND', 'PERMANENT'],
    [{ status: 503 }, 'UPSTREAM_UNAVAILABLE', 'TRANSIENT'], [{ status: 302 }, 'UPSTREAM_UNEXPECTED_STATUS', 'PERMANENT'],
    [{ status: 200, raw: '{"agents": [' }, 'UPSTREAM_INVALID_JSON', 'PERMANENT'], [{ status: 200, raw: 'x'.repeat(2000) }, 'UPSTREAM_RESPONSE_TOO_LARGE', 'PERMANENT']];
  for (const [reply, code, kind] of expectations) {
    await assert.rejects(call(reply), (e: AtlasError) => e.code === code && e.kind === kind
      && !/c2VjcmV0|organization_id|agents/.test(JSON.stringify({ message: e.message, details: e.details })), `${reply.status} ${code}`);
  }
  await assert.rejects(call({ status: 429, headers: { 'retry-after': '30' } }), (e: AtlasError) => e.details.retryAfterSeconds === '30');
  const failing = async () => { throw new TypeError('fetch failed: getaddrinfo ENOTFOUND api.huntress.io'); };
  await assert.rejects(getJson(failing, url, {}), (e: AtlasError) => e.code === 'UPSTREAM_UNAVAILABLE' && e.kind === 'TRANSIENT' && !e.message.includes('ENOTFOUND'));
  assert.equal(retryAfterSeconds('120'), '120');
  assert.equal(retryAfterSeconds('99999'), '3600');
  assert.equal(retryAfterSeconds(new Date(Date.UTC(2026, 9, 7, 8, 1, 0)).toUTCString(), Date.UTC(2026, 9, 7, 8, 0, 0)), '60');
  assert.equal(retryAfterSeconds('soon'), '60');
});

test('untrusted text is storable and bounded; timestamps are UTC, never machine-local', () => {
  assert.equal(safeText('a\u0000b\nc\ud800d   e', 100), 'a b c�d e');
  assert.equal(safeText('😀'.repeat(10), 3), '😀😀😀');
  assert.equal(optionalTime('2026-10-07T08:00:00+02:00', 'f'), '2026-10-07T06:00:00.000Z');
  assert.equal(optionalTime('2026-10-07T08:00:00.1234567', 'f', true), '2026-10-07T08:00:00.123Z');
  assert.throws(() => optionalTime('2026-10-07T08:00:00', 'f'), /UPSTREAM_CONTRACT_MISMATCH/, 'no zone and no explicit rule: refused');
  assert.throws(() => optionalTime('07.10.2026 08:00', 'f', true), /UPSTREAM_CONTRACT_MISMATCH/);
});
